#!/usr/bin/env python3
"""Renders ASCII 32..126 from DejaVu Sans Mono Bold (Bitstream Vera licence) into
4-bit alpha glyphs for the menu: writes src/font_data.h."""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 16, 30, 24
ttf = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
f = ImageFont.truetype(ttf, SIZE)
asc, desc = f.getmetrics()
out = ['/* generated by tools/mkfont.py from DejaVu Sans Mono Bold (Bitstream Vera licence) */',
       '#define FONT_W %d' % W, '#define FONT_H %d' % H,
       '/* 4-bit alpha, two pixels per byte (high nibble first), row-major, chars 32..126 */',
       'static const unsigned char font_data[95][%d] = {' % (W * H // 2)]
for c in range(32, 127):
    im = Image.new('L', (W, H), 0)
    ImageDraw.Draw(im).text((0, (H - asc - desc) // 2), chr(c), font=f, fill=255)
    px = list(im.getdata())
    b = []
    for i in range(0, len(px), 2):
        b.append(((px[i] + 8) // 17) << 4 | ((px[i + 1] + 8) // 17))
    out.append('{' + ','.join(str(x) for x in b) + '},')
out.append('};')
open('src/font_data.h', 'w').write('\n'.join(out) + '\n')
