/* ---- anti-aliasing of the displayed picture (video.c) ---- */

int spu_aa_available(void) { return M.on && !M.dead && M.nspu > 0; }

/* the SPUs smooth the w x h picture at in_ea into out_ea (rows pitch bytes apart)
   once the RSX label at label_ea holds label_value; one band of rows per SPU */
int spu_aa_start(uint64_t in_ea, uint64_t out_ea, uint64_t label_ea, uint32_t label_value,
                 unsigned w, unsigned h, unsigned pitch)
{
    int i, n;
    if (!spu_aa_available() || w > AA_MAX_W || (w & 3) || !h) return 0;
    M.aseq++;
    n = M.nspu;
    for (i = 0; i < n; i++) {
        aa_job *J = &M.ajobs[i];
        J->in_ea = in_ea; J->out_ea = out_ea; J->label_ea = label_ea;
        J->done_ea = (uint64_t)(uintptr_t)&M.adone[i * 32];
        J->width = w; J->height = h; J->pitch = pitch;
        J->y0 = h * (unsigned)i / (unsigned)n; J->y1 = h * (unsigned)(i + 1) / (unsigned)n;
        J->label_value = label_value; J->seq = M.aseq;
        J->timeout = (uint32_t)(tb_freq() / 5);           /* 200 ms of decrementer ticks */
#ifdef HOST_TEST
        host_spu_mailbox((uint64_t)(uintptr_t)M.jobs, (uint64_t)(uintptr_t)M.ajobs, 0x100u + (uint32_t)i);
#else
        __asm__ volatile("sync" : : : "memory");
        sysSpuThreadWriteMb(M.thr[i], 0x100u + (uint32_t)i);
#endif
    }
    M.aband = n;
    return 1;
}

/* 1 when every band of the last frame is done (waits up to max_us), 0 when not
   (yet), -1 when an SPU gave up waiting for the RSX */
int spu_aa_wait(unsigned max_us)
{
    uint64_t t0 = now(), lim = tb_freq() / 1000000u * max_us;
    int i, gave_up = 0;
    for (i = 0; i < M.aband; i++) {
        for (;;) {
            uint32_t d = M.adone[i * 32];
            if ((d & 0x7fffffffu) == M.aseq) { if (d & 0x80000000u) gave_up = 1; break; }
            if (now() - t0 > lim) { M.aa_late++; M.aa_wait_ticks += now() - t0; return 0; }
        }
    }
#ifndef HOST_TEST
    __asm__ volatile("lwsync" : : : "memory");
#endif
    M.aa_wait_ticks += now() - t0;
    M.aa_frames++;
    return gave_up ? -1 : 1;
}

void spu_aa_stats(unsigned *frames, unsigned *late, double *wait_ms)
{
    *frames = M.aa_frames; *late = M.aa_late; *wait_ms = M.aa_wait_ticks * 1000.0 / (double)tb_freq();
    M.aa_frames = M.aa_late = 0; M.aa_wait_ticks = 0;
}

/* installs or removes the core hooks (the setting) */
void spu_mdec_enable(int on)
{
    on = on && M.on && !M.dead;
    if (!on && M.njob) wait_all();
    M.nmb = M.njob = 0;
    mdec_stream_hook = on ? stream_hook : 0;
    mdec_decode_hook = on ? decode_hook : 0;
}
